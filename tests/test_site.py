"""Static checks on the published page, site/index.html.

The page is generated by scripts/build_article.py. These checks need no
browser: every chart slot has figure data, every figure is used, no prose
placeholder survived, and the document is complete.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

from solar_analytics.figures import FIGURES

ROOT = Path(__file__).resolve().parents[1]
HTML = (ROOT / "site" / "index.html").read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def figs() -> dict:
    m = re.search(r"const FIGS=(\{.*?\});</script>", HTML, re.S)
    assert m, "embedded figure data not found"
    return json.loads(m.group(1))


def test_document_is_complete():
    assert HTML.lstrip().lower().startswith("<!doctype html>")
    assert "<title>" in HTML and "</html>" in HTML


def test_every_slot_has_data(figs):
    slots = re.findall(r'data-fig="([a-z_]+)"', HTML)
    assert slots, "no chart slots on the page"
    missing = [s for s in slots if s not in figs]
    assert not missing, f"chart slots without data: {missing}"


def test_every_defined_figure_is_published(figs):
    slots = set(re.findall(r'data-fig="([a-z_]+)"', HTML))
    assert set(FIGURES) == slots, f"unused: {set(FIGURES) - slots}, unknown: {slots - set(FIGURES)}"


def test_no_unfilled_placeholders():
    visible = re.sub(r"<script.*?</script>", "", HTML, flags=re.S)
    assert "[[" not in visible and "{{" not in visible


def test_colours_are_theme_tokens(figs):
    """Chart colours come from the page's CSS tokens, so text and charts share one palette."""
    blob = json.dumps(figs)
    assert "@pv" in blob and "@sun" in blob
    assert "#2B6350" not in blob.upper()


def test_plotly_loaded_from_pinned_cdn():
    assert re.search(r'cdnjs\.cloudflare\.com/ajax/libs/plotly\.js/\d+\.\d+\.\d+/', HTML)


def test_light_theme_only():
    """The page stays white even on a device in dark mode."""
    assert "prefers-color-scheme: dark" not in HTML and 'data-theme="dark"' not in HTML
    assert '<meta name="color-scheme" content="light">' in HTML
